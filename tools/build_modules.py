"""Generate Ruby module metadata from the bilingual installer manifest."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
rows=json.loads((ROOT/'modules.json').read_text(encoding='utf8'))
assert len({r['id'] for r in rows})==len(rows)
assert {r['id'] for r in rows if not r['default']}=={'legacy_shortcuts','battle_support','debug'}
for row in rows:
    for key in ['name_ru','name_en','description_ru','description_en','group_ru','group_en']:assert row[key]
    assert set(row['requires'])<={r['id'] for r in rows}
def ruby(value):return json.dumps(value,ensure_ascii=False)
text='# encoding: UTF-8\n# Generated by tools/build_modules.py from modules.json.\nmodule BS2Suite\n'
for name,values in [('IDS',[r['id'] for r in rows]),('NAMES',[r['name_ru'] for r in rows]),('DESCRIPTIONS',[r['description_ru'] for r in rows]),('DEFAULT_MODULES',[r['id'] for r in rows if r['default']])]:
    text+='  '+name+'='+ruby(values)+'.freeze\n'
text+="  MODULE_ALIASES={'effects'=>'reference_cards','controls'=>'basic_qol','run_toggle'=>'basic_qol','sound'=>'basic_qol','learned_books'=>'basic_qol'}.freeze\n"
text+='  MODULE_REQUIRES={'+','.join(ruby(r['id'])+'=>'+ruby(r['requires']) for r in rows)+'}.freeze\n'
text+='''  module ModuleSelection
    def self.expand(selected)
      values=selected.select { |id| IDS.include?(id) }.uniq
      loop do
        previous=values.dup
        values.dup.each { |id| values|=MODULE_REQUIRES[id] }
        break if previous==values
      end
      IDS.select { |id| values.include?(id) }
    end
    def self.toggle(selected,id)
      values=selected.dup
      if values.include?(id)
        values.delete(id)
        loop do
          previous=values.dup
          values.delete_if { |name| MODULE_REQUIRES[name].any? { |dependency| !values.include?(dependency) } }
          break if previous==values
        end
        values
      else
        expand(values+[id])
      end
    end
  end
end
'''
(ROOT/'mod/BS2Suite/module_config.rb').write_text(text,encoding='utf8',newline='\n')
print(json.dumps({'result':'PASS','modules':len(rows),'default_off':[r['id'] for r in rows if not r['default']]}))
